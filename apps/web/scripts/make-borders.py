#!/usr/bin/env python3
"""Writes src/lib/map/borders-data.ts: the outlines of mainland Portugal and of southern France,
where the satellite map uses their national orthophotos instead of Spain's (map/ortho.ts).

From Natural Earth's 1:10m countries (public domain):

    python3 scripts/make-borders.py ne_10m_admin_0_countries.geojson

Each outline is drawn 300 m inside the border, so that what is taken for Portugal or France is
surely theirs (Spain's orthophotos reach a little across it), and simplified to about 300 m.
"""

import json
import sys
from pathlib import Path

from shapely.geometry import box, mapping, shape

# What is drawn of France: the south, as far north as the street map goes (deploy/vps/maps.sh).
FRANCE_BOX = box(-2.0, 42.0, 4.6, 44.0)
INSET_DEG = 0.003
TOLERANCE_DEG = 0.003


def largest(geometry):
    parts = getattr(geometry, "geoms", [geometry])
    return max(parts, key=lambda part: part.area)


def outline(geometry):
    inner = largest(geometry.buffer(-INSET_DEG)).simplify(TOLERANCE_DEG)
    ring = mapping(inner)["coordinates"][0]
    return [[round(lon, 4), round(lat, 4)] for lon, lat in ring]


def main(path: str) -> None:
    countries = json.loads(Path(path).read_text())["features"]
    by_name = {c["properties"]["ADMIN"]: shape(c["geometry"]) for c in countries}
    portugal = outline(largest(by_name["Portugal"]))
    france = outline(by_name["France"].intersection(FRANCE_BOX))
    out = Path(__file__).parent.parent / "src/lib/map/borders-data.ts"
    out.write_text(
        "// Generated by scripts/make-borders.py from Natural Earth (public domain). Do not edit.\n\n"
        "/** Mainland Portugal, 300 m inside its border: [longitude, latitude], closed. */\n"
        f"export const PORTUGAL: readonly (readonly [number, number])[] = {json.dumps(portugal)};\n\n"
        "/** France up to 44° N, 300 m inside its border: [longitude, latitude], closed. */\n"
        f"export const FRANCE_SOUTH: readonly (readonly [number, number])[] = {json.dumps(france)};\n"
    )
    print(f"{out}: Portugal {len(portugal)} points, France {len(france)} points")


if __name__ == "__main__":
    main(sys.argv[1])
